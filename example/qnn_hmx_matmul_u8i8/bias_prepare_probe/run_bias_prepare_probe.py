#!/usr/bin/env python3
"""Reproduce the u8i8 HTP prepare bias-sidecar probes.

This example isolates the path:

    float Conv(A,W,B) -> quantized DLC static B -> HTP prepare bias_to_vtcm

It does not run the device.  The current mismatch is already visible in the
context binary generated by qnn-context-binary-generator.
"""

